export const POPULAR_EMOJIS: EmojiEntry[] = [
  EMOJI_LIST.find((e) => e.name === "joy")!,
  EMOJI_LIST.find((e) => e.name === "fire")!,
  EMOJI_LIST.find((e) => e.name === "heart")!,
  EMOJI_LIST.find((e) => e.name === "thumbsup")!,
  EMOJI_LIST.find((e) => e.name === "tada")!,
  EMOJI_LIST.find((e) => e.name === "skull")!,
  EMOJI_LIST.find((e) => e.name === "eyes")!,
  EMOJI_LIST.find((e) => e.name === "sparkles")!,
  EMOJI_LIST.find((e) => e.name === "thinking")!,
  EMOJI_LIST.find((e) => e.name === "sob")!,
].filter(Boolean);

const SHORTCODE_MAP = new Map<string, EmojiEntry>();
for (const entry of EMOJI_LIST) {
  SHORTCODE_MAP.set(entry.name.toLowerCase(), entry);
  for (const k of entry.keywords) {
    if (!SHORTCODE_MAP.has(k.toLowerCase())) {
      SHORTCODE_MAP.set(k.toLowerCase(), entry);
    }
  }
}

export function findEmojiByShortcode(code: string): EmojiEntry | undefined {
  const normalized = code.toLowerCase().replace(/^:|:$/g, "").trim();
  return SHORTCODE_MAP.get(normalized);
}

export function searchEmojis(query: string, limit = 6): EmojiEntry[] {
  const q = query.toLowerCase().replace(/^:|:$/g, "").trim();
  if (!q) {
    return POPULAR_EMOJIS.slice(0, limit);
  }

  const exact: EmojiEntry[] = [];
  const prefix: EmojiEntry[] = [];
  const keyword: EmojiEntry[] = [];
  const seen = new Set<string>();

  for (const item of EMOJI_LIST) {
    const name = item.name.toLowerCase();
    if (name === q) {
      exact.push(item);
      seen.add(item.name);
    }
  }

  for (const item of EMOJI_LIST) {
    if (seen.has(item.name)) continue;
    const name = item.name.toLowerCase();
    if (name.startsWith(q)) {
      prefix.push(item);
      seen.add(item.name);
    }
  }

  for (const item of EMOJI_LIST) {
    if (seen.has(item.name)) continue;
    const name = item.name.toLowerCase();
    const hasMatch =
      name.includes(q) ||
      item.keywords.some((k) => k.toLowerCase().startsWith(q) || k.toLowerCase().includes(q));
    if (hasMatch) {
      keyword.push(item);
      seen.add(item.name);
    }
  }

  return [...exact, ...prefix, ...keyword].slice(0, limit);
}
